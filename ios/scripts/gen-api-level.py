#!/usr/bin/env python3
"""Writes QuickrCore/APILevel.swift from shared/api-level.json (docs/specs/client-versions.md §2).

The app and every extension link QuickrCore, so every process has `APILevel.current` with no
Info.plist key or build phase. `make api-level` runs it with the other generated copies:

    python3 ios/scripts/gen-api-level.py [--check]

`--check` exits 1 instead of writing when the committed file is stale (the `api level` CI check).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "shared/api-level.json"
OUT = ROOT / "ios/QuickrKit/Sources/QuickrCore/APILevel.swift"


def render(api_level: int) -> str:
    if type(api_level) is not int or api_level < 0:
        raise SystemExit(f"{SOURCE.name}: api_level must be a non-negative integer")
    return (
        "// Generated by ios/scripts/gen-api-level.py from shared/api-level.json (`make api-level`).\n"
        "// Do not edit.\n"
        "\n"
        "/// The API level this build speaks (docs/specs/client-versions.md §2): sent on every request in\n"
        "/// `X-QuickR-Client`, and compared with the server's `X-QuickR-Min-Client-Level` and\n"
        "/// `X-QuickR-Api-Level`.\n"
        "public enum APILevel {\n"
        f"    public static let current = {api_level}\n"
        "}\n"
    )


def main() -> int:
    text = render(json.loads(SOURCE.read_text())["api_level"])
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale: run make api-level", file=sys.stderr
            )
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
