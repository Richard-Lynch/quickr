"""Request goldens from the Swift client: ``shared/fixtures/requests/*.json``.

The iOS client's tests (``RequestGoldenTests``) write one file per request it can send
that has a body or mutates: ``{operation_id, request: {method, path, headers, body}}``,
named ``<operationId>[.<variant>].json``. They are generated by Swift (never by hand):
``QUICKR_UPDATE_VECTORS=1 swift test --filter RequestGolden`` in ``ios/QuickrKit``.

Here each golden is checked against the server:

- its operation exists, with that method and a path that fits the operation's template;
- its body validates against the operation's Pydantic request model (``extra="forbid"``,
  so an unknown or misspelt key fails), and a bodiless operation has no body;
- it carries ``X-QuickR-Channel: ios`` and, on a mutation, both precondition headers;
- replayed through the app, with the placeholder identity it is rejected by the F10
  precondition (409 ``server_mismatch``) before any effect, and with the real identity
  and ids substituted it gets the status in ``EXPECTED``. Each golden's setup (``SETUP``)
  builds the state it needs from other goldens; the run goldens replay one run's taps in
  order, on a server clock frozen just after them (``RUN_NOW``).

``test_every_mutation_has_a_golden`` is G1 for requests: every non-GET operation in the
app has at least one golden.

``QUICKR_REQUEST_GOLDENS_DIR`` points the contract and replay tests at another set: an old
client's goldens, for compat/old-requests.sh (docs/ios/specs/compatibility.md §3).
"""

