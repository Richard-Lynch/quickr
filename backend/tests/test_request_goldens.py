def load(name: str) -> dict[str, Any]:
    golden: dict[str, Any] = json.loads((REQUESTS_DIR / f"{name}.json").read_text())
    return golden


GOLDENS = sorted(p.name.removesuffix(".json") for p in REQUESTS_DIR.glob("*.json"))


def operations() -> dict[str, tuple[str, str]]:
    """operationId -> (METHOD, path template)."""
    from app.main import app

    return {
        op["operationId"]: (method.upper(), path)
        for path, item in app.openapi()["paths"].items()
        for method, op in item.items()
    }


def template_regex(template: str) -> re.Pattern[str]:
    return re.compile(re.sub(r"\\\{[^}]+\\\}", "[^/?]+", re.escape(template)) + r"(\?.*)?")


# --- static checks -----------------------------------------------------------------------


def test_goldens_exist_and_have_expectations() -> None:
    assert GOLDENS, "no request goldens: run the Swift RequestGoldenTests with QUICKR_UPDATE_VECTORS=1"
    assert set(GOLDENS) == set(EXPECTED), "add the new golden's expected status to EXPECTED"


# Mutations the Swift client doesn't send yet. Each one says when it will.
NO_GOLDEN_YET: dict[str, str] = {}


def test_every_mutation_has_a_golden() -> None:
    covered = {name.split(".")[0] for name in GOLDENS}
    mutations = {op for op, (method, _) in operations().items() if method != "GET"}
    assert mutations - covered == set(NO_GOLDEN_YET), "the Swift client needs a request golden for these"
    assert not set(NO_GOLDEN_YET) & covered, "a stale exclusion: the golden exists now"


@pytest.mark.parametrize("name", GOLDENS)
def test_golden_matches_the_contract(name: str) -> None:
    golden = load(name)
    assert (REQUESTS_DIR / f"{name}.json").read_text() == dump_json(golden), "not canonical JSON"
    op = golden["operation_id"]
    assert name.split(".", maxsplit=1)[0] == op
    method, template = operations()[op]
    request = golden["request"]
    assert request["method"] == method
    assert template_regex(template).fullmatch(request["path"]), (request["path"], template)

    headers = request["headers"]
    assert headers["x-quickr-channel"] == "ios"
    mutation = method != "GET" and op != "checkTopicVersion"
    assert ("x-quickr-expect-server-id" in headers) == mutation
    assert ("x-quickr-expect-epoch" in headers) == mutation

    body = request["body"]
    model = REQUEST_MODELS.get(op)
    if model is None:
        assert body is None, f"{op} takes no body"
        return
    assert headers["content-type"] == "application/json"
    parsed = model.model_validate_json(json.dumps(body))
    # Every key the client sent was read (extra="forbid" also rejects unknown ones).
    assert set(parsed.model_dump(exclude_unset=True)) == set(body)


